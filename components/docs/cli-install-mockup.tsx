async function script(api: MockupApi) {
  const button = getRegistryItem("button");

  // 1. init
  await api.type("npx cubix-ui@latest init");
  if (api.cancelled()) return;
  await api.wait(500);
  api.push("plain", "Need to install the following packages:");
  api.push("plain", "cubix-ui@0.1.4");
  const ok = api.push("plain", "Ok to proceed? (y) ");
  await api.wait(900);
  api.update(ok, "plain", "Ok to proceed? (y) y");
  await api.wait(600);

  const s1 = api.push("spinner", "Writing cubix.json, design tokens, and lib/utils.ts...");
  await api.wait(1300);
  if (api.cancelled()) return;
  api.update(s1, "success", "Wrote cubix.json, design tokens, and lib/utils.ts");
  api.write("cubix.json", cubixJson, "U");
  api.write("app/globals.css", globalsAfter, "M");
  api.write("lib/utils.ts", utilsTs, "U");
  api.open("cubix.json");
  await api.wait(1200);
  api.open("app/globals.css");
  await api.wait(600);
  const s2 = api.push("info", "Installing dependencies...");
  await api.wait(1800);
  if (api.cancelled()) return;
  api.update(s2, "success", "Installed dependencies");
  api.write("package.json", packageAfter, "M");
  api.open("package.json");
  await api.wait(500);
  api.push("success", "Cubix is ready.");
  api.push("dim", "Next: npx cubix-ui@latest add button");
  await api.wait(1400);

  // 2. add button
  await api.type("npx cubix-ui@latest add button");
  if (api.cancelled()) return;
  await api.wait(400);
  const s3 = api.push("spinner", "Adding button...");
  const item = await button;
  await api.wait(1200);
  if (api.cancelled()) return;
  api.update(s3, "success", "Added button (1 file)");
  api.write("components/cubix/button.tsx", item?.files?.[0]?.content ?? "", "U");
  api.open("components/cubix/button.tsx");
  await api.wait(1600);

  // 3. use it
  api.open("app/page.tsx");
  await api.wait(500);
  await api.typeInEditor("app/page.tsx", pageBefore, pageAfter);
  if (api.cancelled()) return;
  await api.wait(500);
  api.showPreview(
    "localhost:3000",
    <div dir="rtl" className="flex h-28 items-center justify-center">
      <Button>دکمه</Button>
    </div>
  );
}

